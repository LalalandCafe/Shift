#!/usr/bin/env node
import fs from "fs";
import path from "path";

const args = process.argv.slice(2);
const dirsArg = args.indexOf("--dirs");
const SCAN_DIRS =
  dirsArg > -1 && args[dirsArg + 1]
    ? args[dirsArg + 1].split(",")
    : ["lib", "app/api", "components"];

const EXTENSIONS = [".js", ".jsx", ".ts", ".tsx", ".mjs"];
const SKIP_DIRS = new Set(["node_modules", ".next", ".git", "public", "dist", "build"]);

const KEYWORDS = [
  "splh", "tplh", "target", "hours", "sales", "eff", "score", "rank",
  "percentile", "ticket", "avgTicket", "overUnder", "over_under", "variance",
  "forecast", "wtd", "ptd", "rating", "review", "band", "pct", "percent",
  "total", "budget", "labor", "transaction", "median", "avg", "average",
  "trainee", "trainer", "comfort", "weight", "blend", "delta", "wow",
];

const MATH = /[-+*/]|Math\.|\btoFixed\b|>=|<=/;

const NOISE = [
  /^\s*(import|export\s+\{|require\()/,
  /className|style=|useState|useEffect|console\.|\.map\(|\.join\(|JSX/,
  /^\s*(<|\/\/ eslint|\* )/,
  /^\s*\}/,
  /padding|margin|width|height|color|fontSize|px"/,
];

function walk(dir, out = []) {
  if (!fs.existsSync(dir)) return out;
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    if (SKIP_DIRS.has(entry.name)) continue;
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, out);
    else if (EXTENSIONS.includes(path.extname(entry.name))) out.push(full);
  }
  return out;
}

function looksLikeFormula(line) {
  const l = line.trim();
  if (l.length < 6 || l.length > 220) return false;
  if (NOISE.some((re) => re.test(l))) return false;
  if (!MATH.test(l)) return false;
  const lower = l.toLowerCase();
  return KEYWORDS.some((k) => lower.includes(k.toLowerCase()));
}

function extractFile(file) {
  const lines = fs.readFileSync(file, "utf8").split("\n");
  const hits = [];

  lines.forEach((line, i) => {
    const isDecl =
      /^\s*(export\s+)?(async\s+)?function\s+\w+/.test(line) ||
      /^\s*export\s+const\s+[A-Z_]{3,}\s*=/.test(line);

    if (!isDecl && !looksLikeFormula(line)) return;

    let note = "";
    for (let j = i - 1; j >= 0 && j >= i - 3; j--) {
      const prev = lines[j].trim();
      if (/^(\/\/|\*|\/\*)/.test(prev)) {
        note = prev.replace(/^(\/\/|\*|\/\*\*?)\s?/, "").replace(/\*\/$/, "").trim() + (note ? " " + note : "");
      } else if (prev !== "") break;
    }

    hits.push({ line: i + 1, code: line.trim(), note, isDecl });
  });

  return hits;
}

const files = SCAN_DIRS.flatMap((d) => walk(d));
let md = "# SHIFT Formula Reference\n\n";
md += "Auto-generated by `scripts/extract-formulas.mjs` on " + new Date().toISOString().slice(0, 10) + ".\n";
md += "Every line below is a real calculation pulled straight from the source, with its file and line number.\n\n";
md += "Scanned: " + SCAN_DIRS.join(", ") + " (" + files.length + " files)\n\n---\n\n";

let totalHits = 0;

for (const file of files.sort()) {
  const hits = extractFile(file);
  if (!hits.length) continue;
  totalHits += hits.length;

  md += "## `" + file + "`\n\n";
  for (const h of hits) {
    if (h.note) md += "_" + h.note + "_\n\n";
    md += "```js\n" + h.code + "\n```\n";
    md += "<sub>" + file + ":" + h.line + "</sub>\n\n";
  }
  md += "---\n\n";
}

md += "\n**" + totalHits + " calculations found across " + files.length + " files.**\n";

fs.writeFileSync("FORMULAS.md", md);
console.log("Done. " + totalHits + " calculations from " + files.length + " files written to FORMULAS.md");
